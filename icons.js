/**
 * Returns an inline <svg>...</svg> markup string for the named icon.
 * @param {string} name - icon key, matching an assets/icons/<name>.svg file
 * @param {string} [extraClass] - additional class name(s) to append
 */
function iconMarkup(name, extraClass) {
  const inner = ICON_PATHS[name];
  if (!inner) return "";
  const cls = "icon" + (extraClass ? " " + extraClass : "");
  return (
    '<svg class="' +
    cls +
    '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
    inner +
    "</svg>"
  );
}

/**
 * Returns the same icon as a detached SVG DOM element, for code that
 * appends via appendChild rather than innerHTML.
 */
function iconElement(name, extraClass) {
  const wrapper = document.createElement("div");
  wrapper.innerHTML = iconMarkup(name, extraClass);
  return wrapper.firstElementChild;
}
